export function getInfiniteDhikrItem(zeroBasedIdx: number): InfiniteDhikrItem {
  const num = zeroBasedIdx + 1;
  const tpl = DHIKR_CYCLE[zeroBasedIdx % DHIKR_CYCLE.length];
  const cycleRound = Math.floor(zeroBasedIdx / DHIKR_CYCLE.length) + 1;
  return {
    id: `dhikr-stream-${num}`,
    index: num,
    roundLabelBn: `যিকির নং #${toBanglaDigits(num)} · চক্র ${toBanglaDigits(cycleRound)}`,
    roundLabelEn: `Dhikr #${num.toLocaleString()} · Round ${cycleRound.toLocaleString()}`,
    ...tpl,
  };
}
